-- 환불·시스템 보상 요청(#385). Commerce RefundRequested 한 건이 환불 한 행이다. 요청 payload는 받은 문자열 그대로 두고,
-- 결과는 그 원문에 Payment 필드를 더해 만든다(Core가 원문과 JSON 값으로 비교한다).
CREATE TABLE refund (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_request_id VARCHAR(64)  NOT NULL UNIQUE,   -- Commerce 값. 늦은 승인은 late-{paymentId}
    execution_id      UUID         NOT NULL UNIQUE,   -- 결과의 executionId. 요청당 하나이고 바뀌지 않는다
    payment_id        BIGINT       REFERENCES payment(id),  -- 결제를 찾지 못한 FAILED는 NULL
    purpose           VARCHAR(32)  NOT NULL CHECK (purpose IN ('USER_REFUND','SYSTEM_COMPENSATION')),
    amount            BIGINT       NOT NULL CHECK (amount >= 0),
    request_payload   TEXT         NOT NULL,
    status            VARCHAR(16)  NOT NULL
                      CHECK (status IN ('PROCESSING','UNKNOWN','SUCCEEDED','FAILED','NO_CHARGE')),
    failure_code      VARCHAR(100),
    result_version    INTEGER      NOT NULL DEFAULT 0 CHECK (result_version >= 0),
    result_payload    TEXT,                           -- 마지막으로 보낸 결과 payload. 다시 보낼 때 그대로 쓴다
    refunded_amount   BIGINT       NOT NULL DEFAULT 0,  -- 실제로 돌려준 금액(결과의 refundedAmount)
    resolved_at       TIMESTAMP WITH TIME ZONE,       -- 결과를 확정한 시각
    -- 실행(#370·#386). 토스 취소 결과와 재처리 예약. 다음 처리 시각이 지난 PROCESSING·UNKNOWN을 재처리가 집는다
    pg_transaction_key VARCHAR(64) UNIQUE,            -- 토스 cancels[].transactionKey
    attempt_count     INTEGER      NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at   TIMESTAMP WITH TIME ZONE,
    check_deadline_at TIMESTAMP WITH TIME ZONE,       -- 결과 불명 확인 마감. 지나면 사람 확인 뒤 대사
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_refund_result CHECK ((result_version = 0) = (result_payload IS NULL)),
    CONSTRAINT ck_refund_amount CHECK (refunded_amount BETWEEN 0 AND amount)
);
CREATE INDEX ix_refund_payment ON refund(payment_id);
CREATE INDEX ix_refund_due ON refund(purpose, next_attempt_at) WHERE status IN ('PROCESSING','UNKNOWN');
-- 결제당 진행 중인 시스템 보상은 1건이다(REF-ACCEPT-06).
CREATE UNIQUE INDEX uq_refund_active_compensation ON refund(payment_id)
    WHERE purpose = 'SYSTEM_COMPENSATION' AND status IN ('PROCESSING','UNKNOWN');

-- 환불 안의 판매자 주문별 금액. 역정산의 기준. 실행(#370·#386)이 채운다.
CREATE TABLE refund_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id           BIGINT      NOT NULL REFERENCES refund(id),
    seller_order_number VARCHAR(64) NOT NULL,
    amount              BIGINT      NOT NULL CHECK (amount > 0),
    CONSTRAINT uq_refund_item UNIQUE (refund_id, seller_order_number)
);

-- 같은 refund_request_id에 다른 본문이 온 수신 기록. 결과는 보내지 않는다(REF-ACCEPT-02).
CREATE TABLE refund_request_conflict (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_request_id VARCHAR(64)  NOT NULL,
    failure_code      VARCHAR(32)  NOT NULL CHECK (failure_code = 'REQUEST_CONFLICT'),
    request_payload   TEXT         NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_refund_conflict_request ON refund_request_conflict(refund_request_id);
