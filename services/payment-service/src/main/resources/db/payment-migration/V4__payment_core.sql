-- 결제 1건. 주문(Commerce)과는 order_ref 값으로만 연결한다.
CREATE TABLE payment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_ref          VARCHAR(64)  NOT NULL UNIQUE
                       CHECK (char_length(order_ref) BETWEEN 6 AND 50),
    buyer_id           VARCHAR(36)  NOT NULL,
    amount             BIGINT       NOT NULL CHECK (amount > 0),
    refunded_amount    BIGINT       NOT NULL DEFAULT 0,
    status             VARCHAR(32)  NOT NULL,
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    pg_provider        VARCHAR(32)  NOT NULL,
    pg_order_id        VARCHAR(64)  UNIQUE,
    checkout_seq       INTEGER      NOT NULL DEFAULT 0,
    pg_payment_key     VARCHAR(200) UNIQUE,
    pg_status          VARCHAR(32),
    partial_cancelable BOOLEAN,
    approved_at        TIMESTAMP WITH TIME ZONE,
    approving_at       TIMESTAMP WITH TIME ZONE,
    next_check_at      TIMESTAMP WITH TIME ZONE,
    check_deadline_at  TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_payment_status CHECK (status IN
        ('CREATED','APPROVING','APPROVED','UNKNOWN','CANCELED','PARTIALLY_REFUNDED','REFUNDED')),
    CONSTRAINT ck_payment_refunded CHECK (refunded_amount BETWEEN 0 AND amount)
);
CREATE INDEX ix_payment_check     ON payment(next_check_at) WHERE status = 'UNKNOWN';
CREATE INDEX ix_payment_approving ON payment(approving_at)  WHERE status = 'APPROVING';
CREATE INDEX ix_payment_expiry    ON payment(expires_at)    WHERE status = 'CREATED';

CREATE TABLE payment_seller_amount (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          BIGINT       NOT NULL REFERENCES payment(id),
    seller_order_number VARCHAR(64)  NOT NULL UNIQUE,
    seller_id           VARCHAR(36)  NOT NULL,
    amount              BIGINT       NOT NULL CHECK (amount > 0),
    commission_rate     NUMERIC(5,4) NOT NULL CHECK (commission_rate BETWEEN 0 AND 1)
);
CREATE INDEX ix_psa_payment ON payment_seller_amount(payment_id);

-- PG 호출 기록. 호출 전에 outcome='UNKNOWN'으로 넣고, 응답을 받으면 그 행의 결과만 채운다(#338).
CREATE TABLE pg_call (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      BIGINT      NOT NULL REFERENCES payment(id),
    kind            VARCHAR(16) NOT NULL CHECK (kind IN ('CONFIRM','QUERY','CANCEL')),
    pg_order_id     VARCHAR(64),
    idempotency_key VARCHAR(300),
    outcome         VARCHAR(16) NOT NULL CHECK (outcome IN ('SUCCESS','DECLINED','NOT_SENT','UNKNOWN')),
    http_status     INTEGER,
    result_code     VARCHAR(64),
    requested_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_pg_call_payment ON pg_call(payment_id, id);

-- 원장. 분개는 고치거나 지우지 않는다. 정정은 반대 분개로 한다.
CREATE TABLE ledger_journal (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_type   VARCHAR(32) NOT NULL CHECK (ref_type IN
        ('PAYMENT_APPROVED','REFUND_SUCCEEDED','PURCHASE_CONFIRMED','SETTLEMENT_REVERSED','PAYOUT_COMPLETED')),
    ref_id     VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ledger_journal_ref UNIQUE (ref_type, ref_id)
);
CREATE TABLE ledger_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id BIGINT      NOT NULL REFERENCES ledger_journal(id),
    account    VARCHAR(32) NOT NULL CHECK (account IN
        ('PG_CUSTODY','BUYER_DEPOSIT','SELLER_PAYABLE','COMMISSION_REVENUE')),
    debit      BIGINT      NOT NULL DEFAULT 0,
    credit     BIGINT      NOT NULL DEFAULT 0,
    seller_id  VARCHAR(36),
    CONSTRAINT ck_ledger_side   CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0)),
    CONSTRAINT ck_ledger_seller CHECK (account <> 'SELLER_PAYABLE' OR seller_id IS NOT NULL)
);
CREATE INDEX ix_ledger_entry_journal ON ledger_entry(journal_id);
CREATE INDEX ix_ledger_entry_account ON ledger_entry(account, seller_id);
