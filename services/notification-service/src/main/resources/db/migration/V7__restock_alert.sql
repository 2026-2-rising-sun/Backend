--
-- "이 상품 재입고되면 알려줘" 를 신청한 기록이다. 회원 하나와 상품 하나에 행 하나다.
--
-- 방송 알림 신청(broadcast_alert)과 같은 구조다. 보내는 쪽이 알림이므로 신청 기록도 알림이 가진다.
-- =====================================================================

CREATE TABLE restock_alert (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  VARCHAR(36) NOT NULL,
    product_id BIGINT      NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 같은 상품을 두 번 신청해도 행은 하나다. 두 번째 신청은 오류가 아니라 성공으로 돌려준다.
    CONSTRAINT uk_restock_alert_member_product UNIQUE (member_id, product_id)
);

-- 품절이 풀리면 그 상품의 신청자 전원을 한 번에 찾는다.
CREATE INDEX ix_restock_alert_product_id ON restock_alert (product_id);
