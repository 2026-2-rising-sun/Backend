-- =====================================================================
-- V11__notification_event_id_length.sql  (P3, #292)
--
-- notification.event_id 를 36 에서 64 로 넓힌다.
--
-- 이 컬럼은 (event_id, member_id) 유일 제약으로 같은 알림이 두 번 만들어지는 것을 막는다.
-- 처음에는 이벤트의 UUID 만 들어갈 것으로 보고 36 으로 잡았다.
--
-- 그런데 스케줄러가 만드는 알림은 받은 이벤트가 없다. "언제 보낼지" 만 이벤트로 알아내고
-- 시각이 되면 알림을 만들기 때문에, 중복을 막을 키를 알림이 직접 만들어야 한다.
-- 그 키는 "종류 + 대상 식별자" 모양이라 UUID 보다 길다.
--
--   broadcast-soon-42                                        17자, 우연히 들어갔다
--   payment-expiry-PG-3f2a1b7c-9d4e-4a8b-b1c2-0e5f6a7b8c9d   54자, 들어가지 않는다
--
-- 결제 묶음 번호가 'PG-' + UUID 라서 그 자체로 39 자다. 종류를 앞에 붙이면 36 을 넘는다.
-- 종류를 빼면 실제 이벤트 UUID 와 같은 값이 될 수 있어 빼지 않는다.
--
-- 넓히기만 하므로 기존 행과 유일 제약은 그대로다.
-- SET DATA TYPE 은 PostgreSQL 과 H2 둘 다 쓰는 표준 형식이다.
-- =====================================================================
ALTER TABLE notification ALTER COLUMN event_id SET DATA TYPE VARCHAR(64);
