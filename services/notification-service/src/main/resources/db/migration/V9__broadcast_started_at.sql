--
-- 방송이 실제로 시작한 시각이다. NULL 이면 아직 시작 이벤트를 받지 못했다.
--
-- 왜 필요한가 — 임박 알림 스케줄러는 "아직 안 보냈고 scheduled_at 이 10분 안" 인 방송을
-- 찾는다. 그런데 예정 시각보다 늦게 시작한 방송은 이미 방송 중인데도 이 조건에 그대로
-- 남아 있어서, 보고 있는 사람에게 "곧 시작합니다" 가 간다.
--
--   12:00 예정 → 12:00 지남(알림 안 감, scheduled_at > from 조건에서 빠짐)
--   12:20 실제 시작 → 다음 주기부터 scheduled_at 이 범위 밖이라 안 가지만,
--   반대로 12:00 예정인데 11:55 에 일찍 시작하면 11:50~12:00 창에 그대로 걸린다.
--
-- scheduled_at 을 시작 시각으로 덮어쓰지 않는다. 예정 시각은 일정 이벤트가 준 값이고,
-- 시작 시각은 시작 이벤트가 준 값이다. 한 컬럼에 섞으면 어느 쪽 근거인지 알 수 없다.
--
-- 인덱스는 추가하지 않는다. ix_broadcast_schedule_starting_soon 이 조회 범위를 이미
-- 좁히고, 거기서 걸러질 행은 "곧 시작하는 방송" 수준이라 적다.
-- =====================================================================
ALTER TABLE broadcast_schedule ADD COLUMN started_at TIMESTAMP WITH TIME ZONE;
