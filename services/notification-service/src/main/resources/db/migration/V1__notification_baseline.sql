-- ----- notification --------------------------------------------------
-- 회원 1명에게 보여줄 알림 1건.
--
-- 컬럼은 지금 알림함이 실제로 쓰는 것만 둔다. 알림을 "만드는" 쪽(이벤트 구독)은 아직 없고,
-- 거기에 필요한 컬럼(이벤트 ID·종류, 눌렀을 때 보낼 곳)은 이벤트 계약이 확정된 뒤에 추가한다.
-- 테이블이 비어 있는 동안은 컬럼 추가 비용이 사실상 0 이고, 반대로 지금 모양을 박아두면
-- 계약이 다르게 정해졌을 때 이미 쓰고 있는 스키마를 고치게 된다.
--   → 추가 예정: event_id, event_type (중복 알림 방지의 (event_id, member_id) 유일 제약 포함),
--      link_type, link_value (알림을 눌렀을 때 보낼 곳)
--
-- title, body : 화면에 그대로 보여줄 문구. 알림을 만들 때 완성해서 넣고, 조회할 때 조립하지 않는다.
--               Commerce 가 죽어도 알림함이 보이려면 문구에 쓸 값을 알림이 들고 있어야 한다.
-- occurred_at : 알림이 알리는 일이 실제로 일어난 시각. 목록 정렬 기준이며 저장한 시각(created_at)이 아니다.
--               나중에 이벤트가 늦게 도착하거나 순서가 뒤바뀌어도 사용자에게는 일어난 순서로 보여야 한다.
-- read_at     : 읽은 시각. NULL 이면 안 읽음. "안 받음" 상태는 두지 않는다 —
--               인앱 알림은 이 행이 생긴 순간이 곧 전달이고, 그 뒤에 확인할 구간이 없다.
CREATE TABLE notification (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   VARCHAR(36)  NOT NULL,
    title       VARCHAR(100) NOT NULL,
    body        VARCHAR(500) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 내 알림 목록의 최신순 커서 조회 ((occurred_at, id) < (:cursorAt, :cursorId)).
-- occurred_at 만으로는 부족하다. 방송 시작 알림은 등록자 전원에게 같은 시각으로 한꺼번에 만들어지므로,
-- 같은 시각이 여러 건이면 커서가 가리킬 지점이 모호해져 알림이 누락되거나 두 번 보인다. id 까지 넣어야 한다.
CREATE INDEX ix_notification_member_occurred_at_id ON notification (member_id, occurred_at DESC, id DESC);

-- 안 읽은 개수 세기 (member_id = ? AND read_at IS NULL).
-- PostgreSQL 만 보면 "WHERE read_at IS NULL" 인 부분 인덱스가 더 작고 빠르다. 하지만 테스트가 H2 로
-- 같은 마이그레이션을 돌리고 H2 는 부분 인덱스를 못 만든다. (member_id, read_at) 복합 인덱스도
-- NULL 을 인덱스에 담으므로 같은 조건을 인덱스 탐색으로 처리한다.
-- 알림이 쌓여 이것만으로 부족해지면 그때 PostgreSQL 전용 마이그레이션으로 부분 인덱스를 추가한다.
CREATE INDEX ix_notification_member_read_at ON notification (member_id, read_at);
