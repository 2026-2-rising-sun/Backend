--
-- "이 방송 시작하면 알려줘" 를 신청한 기록이다. 회원 하나와 방송 하나에 행 하나다.
--
-- 왜 알림이 들고 있는가 — 보내는 쪽이 알림이기 때문이다. Live 가 신청자를 들고 있으면
-- 알림을 몇 번 보냈는지, 읽었는지를 아는 곳이 두 군데로 흩어진다. Live 는 방송 시작 사실만
-- 발행하고, 누구에게 보낼지는 알림이 정한다.
-- =====================================================================

CREATE TABLE broadcast_alert (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    VARCHAR(36) NOT NULL,
    broadcast_id BIGINT      NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 같은 방송을 두 번 신청해도 행은 하나다. 두 번째 신청은 오류가 아니라 성공으로 돌려준다.
    CONSTRAINT uk_broadcast_alert_member_broadcast UNIQUE (member_id, broadcast_id)
);

-- 방송이 시작되면 그 방송의 신청자 전원을 한 번에 찾는다. 이 조회가 알림 생성의 시작점이다.
CREATE INDEX ix_broadcast_alert_broadcast_id ON broadcast_alert (broadcast_id);
