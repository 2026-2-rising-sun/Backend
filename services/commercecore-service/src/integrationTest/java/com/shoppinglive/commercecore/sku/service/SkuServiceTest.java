package com.shoppinglive.commercecore.sku.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.clearInvocations;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;

import com.shoppinglive.commercecore.sales.entity.SalesStatus;
import com.shoppinglive.commercecore.sales.exception.InsufficientStockException;
import com.shoppinglive.commercecore.sku.dto.SkuView;
import com.shoppinglive.commercecore.sku.entity.SkuSaleStatus;
import com.shoppinglive.commercecore.sku.event.SkuEventTracker;
import com.shoppinglive.commercecore.sku.repository.SkuRepository;
import com.shoppinglive.common.outbox.EventOutbox;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ContextConfiguration;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.IllegalTransactionStateException;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.support.TransactionTemplate;

@JdbcTest
@ContextConfiguration(classes = {SkuService.class, SkuRepository.class, SkuEventTracker.class})
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@DisplayName("SKU 단일 행 연산·트랜잭션 (H2, Outbox Mock)")
class SkuServiceTest {
    @Autowired private SkuService service;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private PlatformTransactionManager transactionManager;
    @MockitoBean private EventOutbox outbox;
    private TransactionTemplate transaction;

    @BeforeEach
    void setUp() {
        transaction = new TransactionTemplate(transactionManager);
        jdbc.execute("DROP TABLE IF EXISTS sku");
        // H2 업무 테스트용 스키마다. V102의 PostgreSQL 백필·시퀀스 검증은 별도 실행한다.
        jdbc.execute(
                """
                CREATE TABLE sku (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  product_id BIGINT NOT NULL, price BIGINT NOT NULL CHECK(price>0),
                  available INT NOT NULL CHECK(available>=0), reserved INT NOT NULL CHECK(reserved>=0),
                  sale_status VARCHAR(32) NOT NULL CHECK(sale_status IN ('READY','ON_SALE','PRIVATE')),
                  version BIGINT NOT NULL, snapshot_version BIGINT NOT NULL,
                  product_name_snapshot VARCHAR(255) NOT NULL,
                  created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL)
                """);
    }

    @Test
    @DisplayName("같은 상품에 여러 SKU를 생성하고 초기 재고 0과 READY를 유지한다")
    void createsMultipleSkusForProductWithoutReservingOnRead() {
        SkuView first = create(0);
        SkuView second = create(3);
        assertThat(service.findByProductId(7L))
                .extracting(SkuView::skuId)
                .containsExactly(first.skuId(), second.skuId());
        assertThat(first.status()).isEqualTo(SalesStatus.READY);
        assertThat(first.reserved()).isZero();
        assertThat(
                        service.findBySkuIds(
                                List.of(second.skuId(), first.skuId(), second.skuId(), 999L)))
                .extracting(SkuView::skuId)
                .containsExactly(first.skuId(), second.skuId());
    }

    @Test
    @DisplayName("활성 트랜잭션 없는 변경과 거래 잠금은 거절한다")
    void requiresCallerTransaction() {
        assertThatThrownBy(() -> service.create(7L, 19000, 5, "상품"))
                .isInstanceOf(IllegalTransactionStateException.class);
        assertThatThrownBy(() -> service.lockForOrder(List.of(1L)))
                .isInstanceOf(IllegalTransactionStateException.class);
    }

    @Test
    @DisplayName("0재고 판매 시작은 품절로 표시하고 중지 의도와 READY 복귀 금지를 보존한다")
    void derivesSoldOutWithoutOverwritingManualStatus() {
        Long id = create(0).skuId();
        transaction.executeWithoutResult(tx -> service.changeSaleStatus(id, SkuSaleStatus.ON_SALE));
        assertThat(read(id).status()).isEqualTo(SalesStatus.SOLD_OUT);
        transaction.executeWithoutResult(tx -> service.changeSaleStatus(id, SkuSaleStatus.PRIVATE));
        transaction.executeWithoutResult(tx -> service.restock(id, 2));
        assertThat(read(id).status()).isEqualTo(SalesStatus.PRIVATE);
        assertThatThrownBy(
                        () ->
                                transaction.executeWithoutResult(
                                        tx -> service.changeSaleStatus(id, SkuSaleStatus.READY)))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    @DisplayName("예약·소진·해제·환불 복구가 두 수량을 정확히 변경한다")
    void changesOnlyTheStockOwnedByEachOperation() {
        Long id = onSale(5);
        transaction.executeWithoutResult(tx -> service.reserve(id, 3));
        assertStock(id, 2, 3);
        transaction.executeWithoutResult(tx -> service.consume(id, 1));
        assertStock(id, 2, 2);
        transaction.executeWithoutResult(tx -> service.release(id, 2));
        assertStock(id, 4, 0);
        transaction.executeWithoutResult(tx -> service.restock(id, 1));
        assertStock(id, 5, 0);
        assertThatThrownBy(() -> transaction.executeWithoutResult(tx -> service.release(id, 1)))
                .isInstanceOf(IllegalStateException.class);
        assertThatThrownBy(() -> transaction.executeWithoutResult(tx -> service.reserve(id, -1)))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    @DisplayName("가격 변경은 재고를 덮어쓰지 않고 음수와 오버플로 증감을 거절한다")
    void preservesStockWhenChangingPriceAndRejectsOverflow() {
        Long id = onSale(5);
        transaction.executeWithoutResult(
                tx -> {
                    service.reserve(id, 2);
                    service.changePrice(id, 21000);
                });
        assertStock(id, 3, 2);
        assertThat(read(id).price()).isEqualTo(21000);
        assertThatThrownBy(
                        () ->
                                transaction.executeWithoutResult(
                                        tx -> service.adjustAvailable(id, Integer.MAX_VALUE)))
                .isInstanceOf(InsufficientStockException.class);
        assertThatThrownBy(
                        () ->
                                transaction.executeWithoutResult(
                                        tx -> service.adjustAvailable(id, -4)))
                .isInstanceOf(InsufficientStockException.class);
        assertThatThrownBy(() -> transaction.executeWithoutResult(tx -> service.changePrice(id, 0)))
                .isInstanceOf(IllegalArgumentException.class);
        assertStock(id, 3, 2);
    }

    @Test
    @DisplayName("다품목 중 하나가 부족하면 앞선 예약과 Outbox를 함께 롤백한다")
    void rollsBackAllItemsOnShortage() {
        Long first = onSale(5);
        Long second = onSale(0);
        clearInvocations(outbox);
        assertThatThrownBy(
                        () ->
                                transaction.executeWithoutResult(
                                        tx -> {
                                            assertThat(service.lockForOrder(List.of(second, first)))
                                                    .extracting(SkuView::skuId)
                                                    .containsExactly(first, second);
                                            service.reserve(first, 2);
                                            service.reserve(second, 1);
                                        }))
                .isInstanceOf(InsufficientStockException.class);
        assertStock(first, 5, 0);
        verify(outbox, never()).append(anyString(), any());
    }

    @Test
    @DisplayName("Outbox 저장 실패로 커밋하지 못하면 가격과 재고도 롤백한다")
    void rollsBackWhenOutboxFails() {
        Long id = onSale(5);
        doThrow(new IllegalStateException("Outbox 실패")).when(outbox).append(anyString(), any());
        assertThatThrownBy(
                        () ->
                                transaction.executeWithoutResult(
                                        tx -> {
                                            service.changePrice(id, 21000);
                                            service.reserve(id, 2);
                                        }))
                .isInstanceOf(IllegalStateException.class);
        assertStock(id, 5, 0);
        assertThat(read(id).price()).isEqualTo(19000);
    }

    @Test
    @DisplayName("같은 트랜잭션에서 예약 후 해제해 표시가 같으면 이벤트를 만들지 않는다")
    void doesNotPublishUnchangedFinalSnapshot() {
        Long id = onSale(5);
        clearInvocations(outbox);
        transaction.executeWithoutResult(
                tx -> {
                    service.reserve(id, 2);
                    service.release(id, 2);
                });
        verify(outbox, never()).append(anyString(), any());
    }

    @Test
    @DisplayName("재고 5개에 동시 예약 10개가 오면 5개만 성공한다 (H2)")
    void doesNotOversellUnderConcurrentReservations() throws Exception {
        Long id = onSale(5);
        List<Callable<Boolean>> requests = new ArrayList<>();
        for (int i = 0; i < 10; i++)
            requests.add(
                    () -> {
                        try {
                            transaction.executeWithoutResult(tx -> service.reserve(id, 1));
                            return true;
                        } catch (InsufficientStockException expected) {
                            return false;
                        }
                    });
        try (var executor = Executors.newFixedThreadPool(10)) {
            int successes = 0;
            for (var result : executor.invokeAll(requests, 30, TimeUnit.SECONDS)) {
                if (result.get()) successes++;
            }
            assertThat(successes).isEqualTo(5);
        }
        assertStock(id, 0, 5);
    }

    private SkuView create(int available) {
        return transaction.execute(tx -> service.create(7L, 19000, available, "상품"));
    }

    private Long onSale(int available) {
        Long id = create(available).skuId();
        transaction.executeWithoutResult(tx -> service.changeSaleStatus(id, SkuSaleStatus.ON_SALE));
        return id;
    }

    private SkuView read(Long id) {
        return service.findBySkuIds(List.of(id)).getFirst();
    }

    private void assertStock(Long id, int available, int reserved) {
        SkuView view = read(id);
        assertThat(view.available()).isEqualTo(available);
        assertThat(view.reserved()).isEqualTo(reserved);
    }
}
