-- 기존 주문·전달 ID를 재작성하지 않고 새 Payment 계약의 연결과 판매자별 원문을 저장한다.
CREATE TABLE seller_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_group_id BIGINT NOT NULL REFERENCES payment_group(id),
 seller_order_number VARCHAR(64) NOT NULL UNIQUE,
 seller_id VARCHAR(36) NOT NULL,
 total_amount BIGINT NOT NULL CHECK(total_amount>0),
 discount_amount BIGINT NOT NULL CHECK(discount_amount>=0),
 payable_amount BIGINT NOT NULL CHECK(payable_amount>0 AND payable_amount=total_amount-discount_amount),
 commission_rate NUMERIC(5,4) NOT NULL CHECK(commission_rate BETWEEN 0 AND 1),
 UNIQUE(payment_group_id,seller_id)
);
CREATE TABLE order_payment_relay (
 payment_group_id BIGINT PRIMARY KEY REFERENCES payment_group(id),
 remote_payment_id BIGINT UNIQUE,
 pg_order_id VARCHAR(64),
 payment_status VARCHAR(32) NOT NULL,
 approved_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE payment_relay_refund (
 refund_request_id VARCHAR(64) PRIMARY KEY,
 payment_group_id BIGINT NOT NULL REFERENCES payment_group(id),
 remote_payment_id BIGINT NOT NULL UNIQUE,
 amount BIGINT NOT NULL CHECK(amount>0),
 reason VARCHAR(32) NOT NULL CHECK(reason='LATE_APPROVAL'),
 status VARCHAR(16) NOT NULL CHECK(status IN ('REQUESTED','SUCCEEDED','FAILED')),
 approved_at TIMESTAMP WITH TIME ZONE NOT NULL,
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
 completed_at TIMESTAMP WITH TIME ZONE,
 failure_code TEXT
);
ALTER TABLE payment_delivery_request DROP CONSTRAINT payment_delivery_request_kind_check;
ALTER TABLE payment_delivery_request ADD CONSTRAINT payment_delivery_request_kind_check
 CHECK(kind IN ('PAYMENT','REFUND','PREPARE','APPROVAL'));
CREATE UNIQUE INDEX uk_payment_relay_delivery ON payment_delivery_request(payment_group_id,kind)
 WHERE kind IN ('PREPARE','APPROVAL');
