-- 코디네이터 기술 조정으로 V102를 배정했다. 기존 Sales ID와 거래 값을 보존한다.
CREATE TABLE sku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    price BIGINT NOT NULL CHECK (price > 0),
    available INTEGER NOT NULL CHECK (available >= 0),
    reserved INTEGER NOT NULL CHECK (reserved >= 0),
    sale_status VARCHAR(32) NOT NULL CHECK (sale_status IN ('READY','ON_SALE','PRIVATE')),
    version BIGINT NOT NULL DEFAULT 0,
    snapshot_version BIGINT NOT NULL DEFAULT 1 CHECK (snapshot_version > 0),
    product_name_snapshot VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sku_product_id_id ON sku (product_id,id);

-- 재고 누락과 양수 재고의 SOLD_OUT을 조용히 제외하거나 판매 재개하지 않는다.
-- 새 파생 상태와 모순되는 기존 데이터는 NOT NULL 제약으로 이행을 중단해 확인한다.
INSERT INTO sku(id,product_id,price,available,reserved,sale_status,version,
                snapshot_version,product_name_snapshot,created_at,updated_at)
SELECT s.id,s.product_id,s.price,t.available,t.reserved,
       CASE WHEN s.status='SOLD_OUT' AND t.available>0 THEN NULL
            WHEN s.status='SOLD_OUT' THEN 'ON_SALE' ELSE s.status END,
       s.version,s.snapshot_version,s.product_name_snapshot,s.created_at,
       GREATEST(s.updated_at,t.updated_at)
FROM sales_info s LEFT JOIN sales_stock t ON t.sales_info_id=s.id;

-- 명시 ID 백필 뒤 신규 SKU가 기존 ID와 충돌하지 않도록 identity 시퀀스를 맞춘다.
SELECT setval(pg_get_serial_sequence('sku','id'), COALESCE(MAX(id),1), COUNT(*)>0) FROM sku;

