-- Core 업무 상태와 함께 기록하는 Payment 전달 원문 및 결과 적용 사본.
CREATE TABLE payment_delivery_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id VARCHAR(36) NOT NULL UNIQUE,kind VARCHAR(16) NOT NULL CHECK(kind IN ('PAYMENT','REFUND')),
 order_id BIGINT NOT NULL REFERENCES orders(id),payment_group_id BIGINT REFERENCES payment_group(id),
 reference_number VARCHAR(64) NOT NULL,amount BIGINT NOT NULL CHECK(amount>=0),request_key VARCHAR(64) NOT NULL,
 payment_id BIGINT,core_refund_request_id BIGINT UNIQUE REFERENCES refund_request(id),
 command TEXT NOT NULL,result TEXT,status VARCHAR(32) NOT NULL CHECK(status IN ('PROCESSING','UNKNOWN','SUCCESS','FAILED','TIMEOUT')),
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL,next_action_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX uk_payment_delivery_payment ON payment_delivery_request(payment_id) WHERE kind='PAYMENT';
CREATE INDEX ix_payment_delivery_due ON payment_delivery_request(next_action_at,id) WHERE status IN ('PROCESSING','UNKNOWN');
