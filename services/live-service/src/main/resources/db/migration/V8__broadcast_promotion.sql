-- 방송 중 이벤트(프로모션). 쿠폰 전용이 아니라 type + 자유 JSON attributes 로 받아, 라이브는
-- attributes 를 해석하지 않고 저장·전달만 한다. 새 종류(TIME_DEAL 등)는 코드 변경 없이 추가된다.
--
-- 상태 머신: READY -> OPEN -> CLOSED. READY -> CLOSED 는 취소. CLOSED 에서 다시 열 수 없다.
-- 자동 만료는 duration_seconds 가 지정된 OPEN 프로모션에 대해 closes_at 기준으로 스케줄러가 끈다.
CREATE TABLE broadcast_promotion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_id BIGINT NOT NULL REFERENCES broadcast(id),
    request_key VARCHAR(128) NOT NULL UNIQUE,
    fingerprint VARCHAR(64) NOT NULL,
    type VARCHAR(64) NOT NULL,
    title VARCHAR(100) NOT NULL,
    attributes TEXT NOT NULL,
    duration_seconds INTEGER,
    status VARCHAR(16) NOT NULL,
    opened_at TIMESTAMP WITH TIME ZONE,
    closes_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    close_reason VARCHAR(32),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 방송 단위 조회(관리 목록, 공개 조회)에 쓰는 인덱스.
CREATE INDEX idx_broadcast_promotion_broadcast ON broadcast_promotion(broadcast_id, id);

-- 스케줄러가 (OPEN AND closes_at <= now) 로 만료 대상을 긁어가는 전용 인덱스.
-- status 를 함께 두어 OPEN 아닌 행은 인덱스가 커지지 않는다.
CREATE INDEX idx_broadcast_promotion_expiring ON broadcast_promotion(status, closes_at);
