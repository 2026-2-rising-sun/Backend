-- 다른 서비스로 가는 이벤트를 상태 전이와 같은 트랜잭션에 기록한다 (libs/common-outbox).
-- payload 는 직렬화된 이벤트 봉투 전체라 이벤트 종류가 늘어도 이 테이블은 바뀌지 않는다.
CREATE TABLE event_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(36) NOT NULL UNIQUE,
    event_type VARCHAR(128) NOT NULL,
    topic VARCHAR(128) NOT NULL,
    message_key VARCHAR(128) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(500)
);

-- 릴레이는 미발행 행만 id 순으로 읽는다.
CREATE INDEX idx_event_outbox_unpublished ON event_outbox(id) WHERE published_at IS NULL;
