-- 검색 색인할 상품. 사본을 고친 트랜잭션에서 한 줄씩 쌓고, 부분 색인이 상품별로 모아 처리한 뒤 처리한 id까지만 지운다.
-- product_id 를 PK 로 두지 않는다. 같은 상품의 동시 기록이 키 충돌로 사본 반영을 실패시키지 않게 한다.
CREATE TABLE index_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_index_task_product_id ON index_task (product_id, id);

-- ShedLock 잠금. 부분 색인과 전체 색인이 같은 이름을 써서 Pod 가 여러 개여도 한 번에 하나만 돈다.
CREATE TABLE shedlock (
    name VARCHAR(64) PRIMARY KEY,
    lock_until TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_by VARCHAR(255) NOT NULL
);
